// Generates the OneOf assertion files: OneOfAssertions<T0..Tn> and their Should() extensions, for OneOf (1-8 cases)
// and OneOf.Extended (9-32 cases). The output is committed; edit this file, not the generated ones.
//
//   dotnet run eng/GenerateOneOf.cs            write the files
//   dotnet run eng/GenerateOneOf.cs -- --check  fail if a committed file differs from what this would write
using System.Text;

var root = Path.GetFullPath(Path.Combine(AppContext.GetData("EntryPointFileDirectoryPath") as string ?? ".", ".."));
var check = args.Contains("--check");

var files = new (string Path, string Content)[]
{
    ("src/Resultful.AwesomeAssertions.OneOf/OneOfAssertions.cs", Assertions("OneOf", 1, 8)),
    ("src/Resultful.AwesomeAssertions.OneOf/AssertionExtensions.Should.cs", Extensions("OneOf", 1, 8)),
    ("src/Resultful.AwesomeAssertions.OneOf.Extended/OneOfAssertions.cs", Assertions("OneOf.Extended", 9, 32)),
    ("src/Resultful.AwesomeAssertions.OneOf.Extended/AssertionExtensions.Should.cs", Extensions("OneOf.Extended", 9, 32)),
};

var stale = 0;
foreach (var (path, content) in files)
{
    var full = Path.Combine(root, path);
    var current = File.Exists(full) ? File.ReadAllText(full) : null;
    if (current == content)
    {
        continue;
    }

    if (check)
    {
        Console.Error.WriteLine($"{path} differs from eng/GenerateOneOf.cs; run: dotnet run eng/GenerateOneOf.cs");
        stale++;
    }
    else
    {
        File.WriteAllText(full, content);
        Console.WriteLine($"wrote {path}");
    }
}

return stale == 0 ? 0 : 1;

// The namespace line differs by flavor; see Directory.Build.props.
static string Header(string suffix, params string[] relativeUsings)
{
    var sb = new StringBuilder();
    sb.Append("// <auto-generated>Generated by eng/GenerateOneOf.cs. Edit that, not this.</auto-generated>\n");
    sb.Append("using System;\nusing OneOf;\n\n");
    sb.Append($"#if FLUENTASSERTIONS\nnamespace FluentAssertions.{suffix}\n#else\nnamespace Resultful.AwesomeAssertions.{suffix}\n#endif\n{{\n");
    foreach (var u in relativeUsings)
    {
        sb.Append($"    using {u};\n");
    }

    return sb.ToString();
}

static List<string> TypeArgs(int count) => Enumerable.Range(0, count).Select(i => $"T{i}").ToList();

// Ten type arguments per line, continuation lines indented by `tabs` levels of four spaces.
static string Roll(List<string> items, int tabs)
{
    var indent = "\n" + new string(' ', tabs * 4);
    return string.Concat(items.Select((item, i) => i == 0 ? item : (i % 10 == 0 ? "," + indent : ", ") + item));
}

static string Assertions(string suffix, int min, int max)
{
    var classes = new List<string>();
    for (var n = min; n <= max; n++)
    {
        var t = TypeArgs(n);
        classes.Add($$"""
    public class OneOfAssertions<{{Roll(t, 2)}}>
    {
        public OneOfAssertions(OneOf<{{Roll(t, 3)}}> item)
        {
            Subject = item;
        }

        public OneOf<{{Roll(t, 3)}}> Subject { get; }

        public AndConstraint<TResult> BeCase<TResult>(
            string because = "", params object[] becauseArgs)
        {
            var value = Subject.Create();

            var scope = AssertionStart.BecauseOf(because, becauseArgs);

            return new AndConstraint<TResult>(scope.Assert<TResult>(value));
        }

        public AndConstraint<TResultConstraint> BeCase<TResult, TResultConstraint>(
            Func<TResult, TResultConstraint> assertionFunc,
            string because = "", params object[] becauseArgs)
        {
            if (assertionFunc == null)
            {
                throw new ArgumentNullException(nameof(assertionFunc));
            }

            var result = BeCase<TResult>(because, becauseArgs);
            return new AndConstraint<TResultConstraint>(assertionFunc(result.And));
        }
    }
""");
    }

    return Header(suffix, "Union.Models", "Union.Utils") + "\n" + string.Join("\n\n", classes) + "\n}\n";
}

static string Extensions(string suffix, int min, int max)
{
    var methods = new List<string>();
    for (var n = min; n <= max; n++)
    {
        var t = TypeArgs(n);
        methods.Add($$"""
        public static OneOfAssertions<{{Roll(t, 3)}}> Should<{{Roll(t, 3)}}>(
            this OneOf<{{Roll(t, 3)}}> item)
            => new(item);
""");
    }

    return Header(suffix) + "    public static partial class AssertionExtensions\n    {\n"
        + string.Join("\n\n", methods) + "\n    }\n}\n";
}
